# ============================================================
# LOAD SW REFERENCE
# ============================================================
# conv1_pool1_output.mem: one signed int8 per line (decimal or hex)
sw_list = []
with open(SW_REF_FILE, 'r') as f:
    for line in f:
        line = line.strip()
        if not line or line.startswith('//'):
            continue
        # Try hex first (mem files store bare hex like 'ff', '8d', '10')
        # Fall back to decimal
        try:
            val = int(line, 16)
        except ValueError:
            val = int(line)
        # interpret as signed int8
        if val > 127:
            val -= 256
        sw_list.append(val)

sw_arr = np.array(sw_list, dtype=np.int32)
